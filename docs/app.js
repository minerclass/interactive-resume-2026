let activeExperienceFilter = "All";
let activeResourceFilter = "All";

function uniqueDomains() {
  return ["All", ...new Set(experiences.flatMap((item) => item.domains))];
}

function uniqueResourceTypes() {
  return ["All", ...new Set(resources.map((item) => item.type))];
}

function makeTag(text) {
  return `<span class="tag">${text}</span>`;
}

function renderPathways() {
  const container = document.querySelector("#pathwayGrid");
  container.innerHTML = pathways.map((item) => `
    <article class="card pathway-card">
      <div>
        <h3>${item.title}</h3>
        <p>${item.summary}</p>
      </div>
      <div class="tag-row">${item.tags.map(makeTag).join("")}</div>
    </article>
  `).join("");
}

function renderExperienceFilters() {
  const container = document.querySelector("#experienceFilters");
  container.innerHTML = uniqueDomains().map((domain) => `
    <button class="filter-button" type="button" aria-pressed="${domain === activeExperienceFilter}" data-filter="${domain}">
      ${domain}
    </button>
  `).join("");

  container.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => {
      activeExperienceFilter = button.dataset.filter;
      renderExperienceFilters();
      renderExperiences();
    });
  });
}

function renderExperiences() {
  const container = document.querySelector("#experienceTimeline");
  const filtered = experiences.filter((item) => activeExperienceFilter === "All" || item.domains.includes(activeExperienceFilter));

  container.innerHTML = filtered.map((item) => `
    <article class="card timeline-card" data-primary-domain="${slugify(item.domains[0])}">
      <h3>${item.role}</h3>
      <p class="timeline-meta">${item.organization} | ${item.period}</p>
      <ul>${item.bullets.map((bullet) => `<li>${bullet}</li>`).join("")}</ul>
      <div class="tag-row">${item.domains.map(makeTag).join("")}</div>
    </article>
  `).join("");
}

function slugify(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function renderEvidence() {
  const container = document.querySelector("#evidenceGrid");
  container.innerHTML = evidence.map((item) => `
    <article class="card">
      <h3>${item.title}</h3>
      <p>${item.summary}</p>
      <div class="tag-row">${item.examples.map(makeTag).join("")}</div>
    </article>
  `).join("");
}

function renderRepos() {
  const container = document.querySelector("#repoGrid");
  container.innerHTML = projectRepos.map((item) => {
    const liveLink = item.liveLink
      ? `<a class="button primary" href="${item.liveLink}" target="_blank" rel="noreferrer">Open live page</a>`
      : "";
    const repoLink = item.repoLink
      ? `<a class="button" href="${item.repoLink}" target="_blank" rel="noreferrer">View source</a>`
      : "";

    return `
      <article class="card">
        <span class="resource-type">${item.category}</span>
        <h3>${item.title}</h3>
        <p><strong>${item.status}</strong></p>
        <p>${item.summary}</p>
        <div class="tag-row">${item.tags.map(makeTag).join("")}</div>
        <div class="card-actions">${liveLink}${repoLink}</div>
      </article>
    `;
  }).join("");
}

function renderResourceFilters() {
  const container = document.querySelector("#resourceFilters");
  container.innerHTML = uniqueResourceTypes().map((type) => `
    <button class="filter-button" type="button" aria-pressed="${type === activeResourceFilter}" data-filter="${type}">
      ${type}
    </button>
  `).join("");

  container.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => {
      activeResourceFilter = button.dataset.filter;
      renderResourceFilters();
      renderResources();
    });
  });
}

function renderResources() {
  const container = document.querySelector("#resourceGrid");
  const query = document.querySelector("#resourceSearch").value.trim().toLowerCase();
  const filtered = resources.filter((item) => {
    const typeMatch = activeResourceFilter === "All" || item.type === activeResourceFilter;
    const searchText = [item.type, item.year, item.title, item.venue, ...item.keywords].join(" ").toLowerCase();
    return typeMatch && (!query || searchText.includes(query));
  });

  container.innerHTML = filtered.map((item) => `
    <article class="card resource-card">
      <span class="resource-type">${item.type} | ${item.year}</span>
      <h3>${item.title}</h3>
      <p>${item.venue}</p>
      ${item.link ? `<a class="button" href="${item.link}" target="_blank" rel="noreferrer">Open source</a>` : ""}
    </article>
  `).join("");

  if (!filtered.length) {
    container.innerHTML = `<p>No resources match the current search.</p>`;
  }
}

function renderCredentials() {
  const container = document.querySelector("#credentialGrid");
  container.innerHTML = credentials.map((group) => `
    <article class="card credential-card">
      <h3>${group.title}</h3>
      <ul>${group.items.map((item) => `<li>${item}</li>`).join("")}</ul>
    </article>
  `).join("");
}

function init() {
  renderPathways();
  renderExperienceFilters();
  renderExperiences();
  renderEvidence();
  renderRepos();
  renderResourceFilters();
  renderResources();
  renderCredentials();

  document.querySelector("#resourceSearch").addEventListener("input", renderResources);
  document.querySelector("#printButton").addEventListener("click", () => window.print());
}

init();
